import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { format, resolveConfig } from "prettier";
import {
  bytesToHex,
  concatHex,
  getAddress,
  getCreate2Address,
  hexToBytes,
  keccak256,
  padHex,
  zeroHash,
  type Hex,
} from "viem";

const [artifactPath, interpreterAddress] = process.argv.slice(2);
if (!artifactPath || !interpreterAddress)
  throw new Error("Pass the WalletAmountFlowFactory Foundry artifact and the interpreter address");

const deployer = "0x4e59b44847b379578588920cA78FbF26c0B4956C";
const deployerCodeHash = "0x2fa86add0aed31f33a762c9d88e807c475bd51d0f52bd0955754b2608f7e4989";
const interpreter = getAddress(interpreterAddress);
const artifact = JSON.parse(readFileSync(artifactPath, "utf8")) as {
  metadata: { settings: { compilationTarget: Record<string, string> } };
  bytecode: { object: Hex };
  deployedBytecode: {
    object: Hex;
    immutableReferences: Record<string, { start: number; length: number }[]>;
  };
};
const targets = Object.values(artifact.metadata.settings.compilationTarget);
const immutables = Object.values(artifact.deployedBytecode.immutableReferences);
if (targets.length !== 1 || targets[0] !== "WalletAmountFlowFactory" || immutables.length !== 1)
  throw new Error("Expected a WalletAmountFlowFactory artifact with one interpreter immutable");

const interpreterWord = padHex(interpreter, { size: 32 });
const interpreterBytes = hexToBytes(interpreterWord);
const runtime = hexToBytes(artifact.deployedBytecode.object);
const references = immutables[0] ?? [];
if (!references.length) throw new Error("The factory omits the interpreter reference");
for (const { start, length } of references) {
  if (
    (length !== 20 && length !== 32) ||
    start < 0 ||
    start + length > runtime.length ||
    runtime.slice(start, start + length).some((value) => value !== 0)
  )
    throw new Error("Invalid interpreter immutable reference");
  runtime.set(interpreterBytes.slice(-length), start);
}

const initCode = concatHex([artifact.bytecode.object, interpreterWord]);
const factory = {
  interpreter: interpreter.toLowerCase() as Hex,
  deployer,
  deployerCodeHash,
  address: getCreate2Address({ from: deployer, salt: zeroHash, bytecode: initCode }),
  codeHash: keccak256(bytesToHex(runtime)),
  deploymentData: concatHex([zeroHash, initCode]),
};
const filepath = fileURLToPath(
  new URL("../packages/api/src/flashprofits-wallet-factory.generated.ts", import.meta.url)
);
const source = `// Generated by scripts/generate-flashprofits-wallet-factory.ts from the Flashprofits Forge build.\nexport const walletFactory = ${JSON.stringify(factory, null, 2)} as const;\n`;
writeFileSync(filepath, await format(source, { ...(await resolveConfig(filepath)), filepath }));
